const MARKER = "Generated by tate-rotate-controls.sh";
const BLOCK_START = "# BEGIN tate-rotate-controls";
const BLOCK_END = "# END tate-rotate-controls";

const REMAP_TEXT = `# ${MARKER}
input_player1_analog_dpad_mode = "3"
input_player1_btn_up = "7"
input_player1_btn_right = "5"
input_player1_btn_down = "6"
input_player1_btn_left = "4"
input_player1_btn_x = "8"
input_player1_btn_a = "0"
input_player1_btn_b = "1"
input_player1_btn_y = "9"
`;

const CUSTOM_BLOCK = `${BLOCK_START}
# Keep this filename as custom.sh: Batocera/KNULLI calls /userdata/system/custom.sh on boot.
case "$1" in
    start)
        if [ -f /userdata/system/scripts/tate-rotate-controls.sh ]; then
            /bin/bash /userdata/system/scripts/tate-rotate-controls.sh --refresh-all >/tmp/tate-rotate-controls.log 2>&1
        fi
        ;;
esac
${BLOCK_END}`;

const SHELL_SCRIPT = `#!/bin/bash

# Generate RetroArch game remaps for vertical/TATE arcade games.
# The remap rotates P1 D-pad, left-stick-as-D-pad, and ABXY clockwise.

BIOS_ROOT="\${BIOS_ROOT:-/userdata/bios}"
ROMS_ROOT="\${ROMS_ROOT:-/userdata/roms}"
REMAPPINGS_ROOT="\${REMAPPINGS_ROOT:-/userdata/system/configs/retroarch/config/remaps}"
CACHE_ROOT="\${CACHE_ROOT:-/userdata/system/.cache/tate-rotate-controls}"
MARKER="Generated by tate-rotate-controls.sh"

stream_metadata() {
    file="$1"

    case "$file" in
        *.gz)
            if command -v gzip >/dev/null 2>&1; then
                gzip -dc "$file"
            elif command -v zcat >/dev/null 2>&1; then
                zcat "$file"
            elif command -v busybox >/dev/null 2>&1; then
                busybox gzip -dc "$file"
            else
                return 1
            fi
            ;;
        *)
            cat "$file"
            ;;
    esac
}

build_vertical_cache() {
    dat_file="$1"
    cache_file="$2"

    [ -f "$dat_file" ] || return 1
    mkdir -p "$(dirname "$cache_file")" || return 1

    if [ -f "$cache_file" ] && [ "$cache_file" -nt "$dat_file" ]; then
        return 0
    fi

    tmp_file="\${cache_file}.$$"
    if stream_metadata "$dat_file" | awk '
        /<game name="/ {
            name = $0
            sub(/^.*<game name="/, "", name)
            sub(/".*$/, "", name)
            in_game = 1
            vertical = 0
        }
        in_game && /<video/ && /orientation="vertical"/ {
            vertical = 1
        }
        in_game && /<\\/game>/ {
            if (vertical && name != "") {
                print name
            }
            in_game = 0
            name = ""
            vertical = 0
        }
    ' > "$tmp_file"; then
        mv "$tmp_file" "$cache_file"
    else
        rm -f "$tmp_file"
        return 1
    fi
}

is_vertical_rom() {
    rom_name="$1"
    dat_file="$2"
    cache_file="$3"

    build_vertical_cache "$dat_file" "$cache_file" || return 1
    grep -Fxq "$rom_name" "$cache_file"
}

write_remap_contents() {
    cat <<EOF
# \${MARKER}
input_player1_analog_dpad_mode = "3"
input_player1_btn_up = "7"
input_player1_btn_right = "5"
input_player1_btn_down = "6"
input_player1_btn_left = "4"
input_player1_btn_x = "8"
input_player1_btn_a = "0"
input_player1_btn_b = "1"
input_player1_btn_y = "9"
EOF
}

write_clockwise_remap() {
    remap_core="$1"
    rom_name="$2"
    remap_dir="\${REMAPPINGS_ROOT}/\${remap_core}"
    remap_file="\${remap_dir}/\${rom_name}.rmp"

    mkdir -p "$remap_dir" || return 1

    if [ -f "$remap_file" ] && ! grep -Fq "$MARKER" "$remap_file"; then
        # A hand-made game remap already exists. Keep it as the user's override.
        return 0
    fi

    tmp_file="\${remap_file}.$$"
    write_remap_contents > "$tmp_file" || {
        rm -f "$tmp_file"
        return 1
    }

    if [ -f "$remap_file" ] && cmp -s "$tmp_file" "$remap_file"; then
        rm -f "$tmp_file"
        return 0
    fi

    mv "$tmp_file" "$remap_file"
}

generate_for_rom() {
    core="$1"
    rom_path="$2"

    rom_file="\${rom_path##*/}"
    rom_name="\${rom_file%.*}"
    extra_remap_core=""

    case "$core" in
        mame078plus|mame2003-plus|mame2003plus)
            remap_core="MAME 2003-Plus"
            dat_file="\${BIOS_ROOT}/mame2003-plus/mame2003-plus.xml.gz"
            cache_file="\${CACHE_ROOT}/mame2003-plus.vertical"
            ;;
        mame2010)
            remap_core="MAME 2010"
            dat_file="\${BIOS_ROOT}/mame2010/mame2010.xml.gz"
            cache_file="\${CACHE_ROOT}/mame2010.vertical"
            ;;
        fbneo|fbalpha)
            remap_core="FBNeo"
            extra_remap_core="FinalBurn Neo"
            dat_file="\${BIOS_ROOT}/fbneo/FinalBurn Neo (ClrMame Pro XML, Arcade only).dat"
            cache_file="\${CACHE_ROOT}/fbneo.vertical"
            ;;
        *)
            return 0
            ;;
    esac

    if is_vertical_rom "$rom_name" "$dat_file" "$cache_file"; then
        write_clockwise_remap "$remap_core" "$rom_name"
        [ -n "$extra_remap_core" ] && write_clockwise_remap "$extra_remap_core" "$rom_name"
    fi
}

refresh_folder() {
    core="$1"
    folder="$2"

    [ -d "$folder" ] || return 0

    for rom_path in "$folder"/*.zip "$folder"/*.7z; do
        [ -e "$rom_path" ] || continue
        generate_for_rom "$core" "$rom_path"
    done
}

refresh_all() {
    refresh_folder "mame078plus" "\${ROMS_ROOT}/mame"
    refresh_folder "mame2010" "\${ROMS_ROOT}/mame"
    refresh_folder "fbneo" "\${ROMS_ROOT}/fbneo"
}

case "$1" in
    --refresh-all|refresh-all)
        refresh_all
        ;;
    gameStart)
        emulator="$3"
        core="$4"
        rom_path="$5"
        [ "$emulator" = "libretro" ] || exit 0
        [ -n "$rom_path" ] || exit 0
        generate_for_rom "$core" "$rom_path"
        ;;
esac

exit 0
`;

